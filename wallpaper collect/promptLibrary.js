/**
 * Returns a randomized prompt configuration for a given category
 */
export function getRandomPrompt(categorySlug = 'all', orientation = 'desktop') {
  let catKeys = Object.keys(CATEGORIES_CONFIG);
  if (categorySlug && categorySlug !== 'all' && CATEGORIES_CONFIG[categorySlug]) {
    catKeys = [categorySlug];
  }

  const selectedCatKey = catKeys[Math.floor(Math.random() * catKeys.length)];
  const cat = CATEGORIES_CONFIG[selectedCatKey];
  const style = cat.styles[Math.floor(Math.random() * cat.styles.length)];

  const seed = Math.floor(Math.random() * 9999999);
  const promptText = `${style.subject}, ${style.detail}`;

  const isPortrait = orientation === 'mobile';
  const width = isPortrait ? 1080 : 1920;
  const height = isPortrait ? 1920 : 1080;
  const aspectRatio = isPortrait ? '9:16' : '16:9';

  const titleWords = style.subject
    .split(' ')
    .slice(0, 5)
    .map(w => w.charAt(0).toUpperCase() + w.slice(1))
    .join(' ');

  const title = `${titleWords} ${isPortrait ? 'Phone Wallpaper 4K' : 'Ultra HD 4K'}`;

  const description = `Download high-resolution 4K wallpaper featuring ${style.subject}. ${style.detail.split(',')[0]}. Optimized for desktop monitors, OLED displays, and high-DPI smartphones. 100% free download with zero copyright restrictions on Aevion.`;

  return {
    categorySlug: cat.slug,
    categoryName: cat.name,
    categoryFolder: cat.folder,
    prompt: promptText,
    title,
    description,
    tags: [...new Set([...style.tags, isPortrait ? 'mobile' : 'desktop'])],
    width,
    height,
    aspectRatio,
    orientation: isPortrait ? 'portrait' : 'landscape',
    deviceTarget: isPortrait ? 'mobile' : 'desktop',
    seed
  };
}
