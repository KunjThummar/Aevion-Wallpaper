/**
 * Aevion Wallpaper - Metadata Builder
 * Builds compliant MongoDB schema records with complete copyright verification trails.
 */

export function buildWallpaperRecord({
  id,
  title,
  slug,
  description,
  categorySlug,
  categoryName,
  tags,
  width,
  height,
  aspectRatio,
  orientation,
  deviceTarget,
  dominantColor,
  palette = [],
  pHash,
  sha256,
  fileSizeBytes,
  images,
  cloudinaryPublicId,
  source = 'Aevion AI Generation Engine',
  creatorName = 'Aevion AI Studio'
}) {
  const resolutionText = width >= 3840 ? '3840 × 2160 (4K UHD)' : width >= 2560 ? '2560 × 1440 (2K QHD)' : `${width} × ${height}`;

  return {
    id,
    title,
    slug,
    description,
    categorySlug,
    categoryName,
    tags: Array.isArray(tags) ? tags : [],
    resolution: resolutionText,
    originalWidth: width,
    originalHeight: height,
    aspectRatio,
    orientation,
    deviceTarget: deviceTarget || (orientation === 'portrait' ? 'mobile' : 'desktop'),
    dominantColor: dominantColor || '#090a0f',
    palette,
    fileFormat: 'webp',
    fileSizeBytes: fileSizeBytes || 0,
    pHash: pHash || '',
    sha256: sha256 || '',
    images: {
      originalUrl: images.originalUrl,
      previewUrl: images.previewUrl,
      thumbnailUrl: images.thumbnailUrl
    },
    cloudinaryPublicId: cloudinaryPublicId || '',

    // Copyright & Legal Metadata (Section 5 compliance)
    source,
    creatorName,
    licenseType: 'Creative Commons CC0 1.0 (Public Domain Equivalent)',
    licenseUrl: 'https://creativecommons.org/publicdomain/zero/1.0/',
    attributionText: 'Generated by Aevion AI Studio. Free for commercial & personal use with no copyright restrictions.',
    commercialUseAllowed: true,
    redistributionAllowed: true,
    copyrightVerified: true,
    verifiedAt: new Date().toISOString(),

    // Engagement & State Metrics
    viewsCount: 0,
    downloadsCount: 0,
    favoritesCount: 0,
    isFeatured: Math.random() < 0.25, // 25% chance of being featured on Editor's choice
    status: 'published',
    createdAt: new Date().toISOString()
  };
}
